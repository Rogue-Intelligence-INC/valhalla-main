#!/usr/bin/env python3
"""Generate obfuscated embedded-key sources from the master key file.

Outputs (paths given as arguments):
  --cpp  <path> : native/src/valkey.h  (used by desktop engine.cpp)
  --kt   <path> : FrameworkKey.kt     (used by Android apps)

Obfuscation is deliberately light: byte i stored as key[i] ^ 0xA5 ^ (i*7 & 0xFF),
plus a second XOR with a per-file salt constant. This raises the bar against
casual extraction only; it is NOT a substitute for server-issued keys.

The generated files are build inputs and must stay out of git (see .gitignore).
Regenerate with: python tools/gen_key_header.py
"""
import os
import sys

KEY = r"C:\Ai\valhalla-key.bin"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def obfuscate(key):
    return [b ^ 0xA5 ^ ((i * 7) & 0xFF) ^ 0x3C for i, b in enumerate(key)]


def cpp(key):
    enc = obfuscate(key)
    body = ", ".join(f"0x{b:02X}" for b in enc)
    return f"""#pragma once
// Generated by tools/gen_key_header.py - do not commit.
#include <array>
#include <cstdint>
namespace valkey {{
inline std::array<unsigned char, 32> key() {{
    static constexpr unsigned char kEnc[32] = {{{body}}};
    std::array<unsigned char, 32> out{{}};
    for (int i = 0; i < 32; ++i) out[i] = static_cast<unsigned char>(kEnc[i] ^ 0xA5 ^ ((i * 7) & 0xFF) ^ 0x3C);
    return out;
}}
}}  // namespace valkey
"""


def kt(key, package):
    enc = obfuscate(key)
    body = ", ".join(str(b - 256 if b > 127 else b) for b in enc)
    return f"""package {package}

// Generated by tools/gen_key_header.py - do not commit.
object FrameworkKey {{
    private val enc = byteArrayOf({body})
    fun key(): ByteArray = ByteArray(32) {{ i -> (enc[i].toInt() xor 0xA5 xor ((i * 7) and 0xFF) xor 0x3C).toByte() }}
}}
"""


def main():
    key = open(KEY, "rb").read()
    assert len(key) == 32
    targets = [
        (os.path.join(ROOT, "native", "src", "valkey.h"), cpp(key)),
        (os.path.join(ROOT, "student", "android", "app", "src", "main", "java",
                      "com", "rogueintelligence", "valhalla", "student", "FrameworkKey.kt"),
         kt(key, "com.rogueintelligence.valhalla.student")),
        (os.path.join(ROOT, "android", "app", "src", "main", "java",
                      "com", "rogueintelligence", "valhalla", "FrameworkKey.kt"),
         kt(key, "com.rogueintelligence.valhalla")),
    ]
    # main app package may differ; detect from AndroidManifest/source tree
    import glob
    mains = glob.glob(os.path.join(ROOT, "android", "app", "src", "main", "java", "**", "*.kt"), recursive=True)
    pkg = "com.rogueintelligence.valhalla"
    for f in mains:
        with open(f, encoding="utf-8", errors="ignore") as fh:
            for line in fh:
                if line.startswith("package "):
                    pkg = line.split()[1].strip()
                    break
        if pkg != "com.rogueintelligence.valhalla":
            break
    targets[2] = (os.path.join(ROOT, "android", "app", "src", "main", "java", *pkg.split("."), "FrameworkKey.kt"),
                  kt(key, pkg))
    for path, text in targets:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote", path)


if __name__ == "__main__":
    main()
